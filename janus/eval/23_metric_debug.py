#!/usr/bin/env python3
"""
janus/eval/23_metric_debug.py

Metric-debugging suite for the KL sweep -- answers the review questions
"is the lambda=0.25 optimum a bug, memorization, noise, or real?" WITHOUT any
retraining: it reuses the images already generated by the metrics panel
(metrics_panel/<tag>/generated/{before,after}) and only re-scores them.

For each adapter tag it reports, all in one table:
  CMMD_test   distributional distance (CLIP space) of the generations to the
              80 HELD-OUT real images (the headline metric).
  CMMD_train  same, but vs a sample of TRAINING real images. If CMMD_train is
              much lower than CMMD_test for low lambda, the model is matching the
              training set specifically -> memorization (Ivan's concern).
  DINOmmd_test  distributional DINOv2-space distance to held-out reals -- the
              memorization-robust replacement for the nearest-neighbour DINO sim.
  NN_test / NN_train   the current (max-over-nearest) DINO similarity to held-out
              vs training reals. A large NN_train - NN_test gap = near-copying of
              training images.
  ContentPres   mean DINOv2 cosine similarity between the adapter's image and the
              BASE image for the SAME prompt+seed (generated/before vs after) --
              how much of the prompt content survives the style. The property the
              style metrics do not capture; we expect it to FALL as lambda->0.

Reading it:
  * lambda-ranking of CMMD_test == CMMD_train  -> the optimum is signal, not
    small-N noise (Ivan's train-vs-test consistency test passes).
  * NN_train >> NN_test only at low lambda     -> memorization (a real bug-class).
  * ContentPres rising with lambda             -> explains the eye's preference
    for lambda=0.5 (more content preserved), with no metric bug.

Run via 23_run_metric_debug.sh (GPU, ~10 min; no generation).
"""
import json
import os
import random
from glob import glob
from pathlib import Path

import numpy as np
import torch
from PIL import Image
from scipy.spatial.distance import cdist, pdist

MODEL_ID = "deepseek-community/Janus-Pro-7B"
HF_DATASET_NAME = os.environ.get("HF_DATASET_NAME", "lambdalabs/naruto-blip-captions")
HF_IMAGE_COL = os.environ.get("HF_IMAGE_COL", "image")
SEED   = int(os.environ.get("SEED", "42"))
EVAL_N = int(os.environ.get("EVAL_N", "80"))
TRAIN_N = int(os.environ.get("TRAIN_N", "4000"))
N_REF  = int(os.environ.get("N_REF", "80"))   # reals per reference set

MP = Path(os.path.expanduser(
    "~/multimodal-peft/janus/tests/output")) / "metrics_panel"
OUT = Path(os.path.expanduser(
    "~/multimodal-peft/janus/tests/output")) / "metric_debug"

# (label, panel-dir-tag); default = the rank-32 KL sweep.
_DEF = [("kl0",   "gen_7b_kl0_r32__adapter_best"),
        ("kl0.25", "gen_7b_kl025_r32__adapter_best"),
        ("kl0.5", "gen_7b_rank_r32__adapter_best"),
        ("kl1",   "gen_7b_kl1_r32__adapter_best"),
        ("kl1.5", "gen_7b_kl15_r32__adapter_best")]
if os.environ.get("TAGS"):
    TAGS = [(s.split("=")[0], s.split("=")[1]) for s in os.environ["TAGS"].split(";") if "=" in s]
else:
    TAGS = _DEF

_EXT = ("*.png", "*.jpg", "*.jpeg")


def load_dir(d, n=None):
    files = sorted(p for ext in _EXT for p in glob(os.path.join(d, ext)))
    if n:
        files = files[:n]
    return [Image.open(p).convert("RGB") for p in files]


def reals_split():
    """Reproduce the panel's held-out split + a disjoint training sample."""
    from datasets import load_dataset
    ds = load_dataset(HF_DATASET_NAME, split="train")
    ids = list(range(len(ds)))
    random.Random(SEED).shuffle(ids)
    n_eval = min(EVAL_N, 80)
    n_train = min(TRAIN_N, len(ids) - n_eval)
    test_ids = ids[n_train:n_train + n_eval]          # held-out (panel reference)
    train_ids = ids[:N_REF]                            # a sample of the train portion
    test = [ds[i][HF_IMAGE_COL].convert("RGB") for i in test_ids]
    train = [ds[i][HF_IMAGE_COL].convert("RGB") for i in train_ids]
    print(f"  reals: test={len(test)} (held-out) train={len(train)} (sample)", flush=True)
    return test, train


@torch.no_grad()
def clip_feats(imgs, device="cuda", batch=16):
    from transformers import CLIPModel, CLIPProcessor
    proc = CLIPProcessor.from_pretrained("openai/clip-vit-large-patch14")
    clip = CLIPModel.from_pretrained("openai/clip-vit-large-patch14").to(device).eval()

    def to_t(x):
        if torch.is_tensor(x):
            return x
        for a in ("image_features", "pooler_output", "last_hidden_state"):
            v = getattr(x, a, None)
            if torch.is_tensor(v):
                return v if v.dim() == 2 else v[:, 0]
        raise RuntimeError("no clip feats")
    out = []
    for i in range(0, len(imgs), batch):
        x = proc(images=imgs[i:i + batch], return_tensors="pt").to(device)
        f = to_t(clip.get_image_features(**x))
        out.append((f / f.norm(dim=-1, keepdim=True)).cpu().numpy())
    return np.concatenate(out, 0)


@torch.no_grad()
def dino_feats(imgs, device="cuda", batch=8):
    from transformers import AutoImageProcessor, AutoModel
    proc = AutoImageProcessor.from_pretrained("facebook/dinov2-base")
    dino = AutoModel.from_pretrained("facebook/dinov2-base").to(device).eval()
    out = []
    for i in range(0, len(imgs), batch):
        x = proc(images=imgs[i:i + batch], return_tensors="pt").to(device)
        f = dino(**x).last_hidden_state[:, 0]
        out.append((f / f.norm(dim=-1, keepdim=True)).cpu().numpy())
    return np.concatenate(out, 0)


def rbf_mmd2(x, y):
    """Biased RBF-MMD^2 with median-heuristic bandwidth (== the panel CMMD)."""
    sigma = float(np.median(pdist(np.vstack([x, y])))) or 1.0
    kxx = np.exp(-cdist(x, x, "sqeuclidean") / (2 * sigma ** 2))
    kyy = np.exp(-cdist(y, y, "sqeuclidean") / (2 * sigma ** 2))
    kxy = np.exp(-cdist(x, y, "sqeuclidean") / (2 * sigma ** 2))
    return float(kxx.mean() + kyy.mean() - 2 * kxy.mean())


def nn_sim(gen_f, ref_f):
    """Mean over generations of the max cosine sim to the nearest reference."""
    return float((gen_f @ ref_f.T).max(axis=1).mean())


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    test_imgs, train_imgs = reals_split()
    clip_test, clip_train = clip_feats(test_imgs), clip_feats(train_imgs)
    dino_test, dino_train = dino_feats(test_imgs), dino_feats(train_imgs)

    rows = []
    for label, tag in TAGS:
        gdir = MP / tag / "generated"
        after = load_dir(gdir / "after")
        before = load_dir(gdir / "before")
        if not after:
            print(f"  [skip] {label}: no images in {gdir/'after'}", flush=True)
            continue
        ca = clip_feats(after)
        da = dino_feats(after)
        db = dino_feats(before) if before else None
        # content preservation: per-prompt before<->after DINO cosine (aligned by index)
        if db is not None and len(db) == len(da):
            cp = float((da * db).sum(axis=1).mean())
        else:
            cp = float("nan")
        rows.append({
            "label": label, "tag": tag, "n_gen": len(after),
            "CMMD_test":  rbf_mmd2(ca, clip_test),
            "CMMD_train": rbf_mmd2(ca, clip_train),
            "DINOmmd_test": rbf_mmd2(da, dino_test),
            "NN_test":  nn_sim(da, dino_test),
            "NN_train": nn_sim(da, dino_train),
            "ContentPres": cp,
        })
        print(f"  done {label}", flush=True)

    hdr = f"{'lambda':<8}{'CMMD_test':>10}{'CMMD_train':>11}{'DINOmmd':>9}{'NN_test':>9}{'NN_train':>9}{'CtntPres':>9}"
    lines = ["=" * 72, "  metric-debug (KL sweep; reused panel images, no retraining)", hdr, "-" * 72]
    for r in rows:
        lines.append(f"{r['label']:<8}{r['CMMD_test']:>10.4f}{r['CMMD_train']:>11.4f}"
                     f"{r['DINOmmd_test']:>9.4f}{r['NN_test']:>9.4f}{r['NN_train']:>9.4f}{r['ContentPres']:>9.4f}")
    report = "\n".join(lines)
    print("\n" + report)
    (OUT / "metric_debug.txt").write_text(report + "\n", encoding="utf-8")
    (OUT / "metric_debug.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    print(f"\n  saved -> {OUT}/metric_debug.txt (+ .json)")


if __name__ == "__main__":
    main()
