#!/usr/bin/env python3
"""
janus/eval/24_vlm_judge.py

LLM-as-judge for the KL sweep, with an INDEPENDENT open VLM (Qwen2-VL-7B by
default -- NOT Janus, to avoid a self-evaluation circularity). It operationalises
"which image looks better" so we can confront the eye with the style metrics.

Design (kept deliberately rigorous):
  * PAIRWISE: compare two configs (PAIR, default kl0.25 vs kl0.5 -- the contested
    pair) on the SAME prompt; far cleaner for a 7B judge than ranking 5 images.
  * COUNTERBALANCED: every pair is judged in BOTH orders (A,B) and (B,A) so a
    position bias cancels out; we also report the residual position bias.
  * THREE CRITERIA judged separately -> STYLE, CONTENT, OVERALL, so we can see
    WHY one wins (hypothesis: higher lambda preserves CONTENT).
  * BLIND: the judge only sees "Image A / Image B", never the lambda.
  * Deterministic (do_sample=False), so the run is reproducible.

Reuses the images already generated by the metrics panel (no regeneration).
Output: win-rates per config per criterion + Wilson 95% CI + position-bias check.

Run via 24_run_vlm_judge.sh.  Smoke test first: SMOKE=1 (4 prompts).
"""
import json
import math
import os
import random
import re
from pathlib import Path

import torch
from PIL import Image

JUDGE_ID = os.environ.get("JUDGE_ID", "Qwen/Qwen2-VL-7B-Instruct")
SEED   = int(os.environ.get("SEED", "42"))
EVAL_N = int(os.environ.get("EVAL_N", "80"))
TRAIN_N = int(os.environ.get("TRAIN_N", "4000"))
HF_DATASET_NAME = os.environ.get("HF_DATASET_NAME", "lambdalabs/naruto-blip-captions")
HF_IMAGE_COL = os.environ.get("HF_IMAGE_COL", "image")
HF_TEXT_COL  = os.environ.get("HF_TEXT_COL", "text")
N_PROMPTS = int(os.environ.get("N_PROMPTS", "80"))
SMOKE = os.environ.get("SMOKE", "0") == "1"
if SMOKE:
    N_PROMPTS = 4

MP = Path(os.path.expanduser("~/multimodal-peft/janus/tests/output")) / "metrics_panel"
OUT = Path(os.path.expanduser("~/multimodal-peft/janus/tests/output")) / "vlm_judge"

TAG = {"kl0": "gen_7b_kl0_r32__adapter_best", "kl0.25": "gen_7b_kl025_r32__adapter_best",
       "kl0.5": "gen_7b_rank_r32__adapter_best", "kl1": "gen_7b_kl1_r32__adapter_best",
       "kl1.5": "gen_7b_kl15_r32__adapter_best"}
PAIR = os.environ.get("PAIR", "kl0.25,kl0.5").split(",")
C1, C2 = PAIR[0].strip(), PAIR[1].strip()

Z = 1.959963984540054


def wilson(k, n, z=Z):
    if not n:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = (z / d) * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (c - h, c + h)


def eval_prompts():
    from datasets import load_dataset
    ds = load_dataset(HF_DATASET_NAME, split="train")
    ids = list(range(len(ds)))
    random.Random(SEED).shuffle(ids)
    n_eval = min(EVAL_N, 80)
    n_train = min(TRAIN_N, len(ids) - n_eval)
    eval_ids = ids[n_train:n_train + n_eval]
    return [ds[i][HF_TEXT_COL] for i in eval_ids]


def load_imgs(tag, n):
    d = MP / tag / "generated" / "after"
    files = sorted(d.glob("*.png"))[:n]
    return [Image.open(p).convert("RGB").resize((512, 512)) for p in files]


RUBRIC = (
    "You are an expert judge of anime-style image generation. The target is the "
    'prompt "{prompt}", rendered in the Naruto anime art style (bold black ink '
    "outlines, flat cel shading, saturated colours, anime facial features and "
    "proportions). You are shown Image A and Image B: the SAME target produced by "
    "two different generation settings. Compare them on three criteria:\n"
    "- STYLE: which image more convincingly adopts the Naruto/anime art style "
    "(line work, cel shading, character design) rather than a photorealistic or "
    "generic look?\n"
    "- CONTENT: which image more faithfully and coherently depicts the target "
    'subject and composition of "{prompt}" (recognisable subject, intact '
    "structure, fewer artifacts)?\n"
    "- OVERALL: which is the better Naruto-style rendition of the target, "
    "balancing style and content?\n"
    "First reason briefly (one short sentence per criterion), then end your reply "
    "with EXACTLY these three lines:\n"
    "STYLE: <A or B>\nCONTENT: <A or B>\nOVERALL: <A or B>"
)
_PAT = {c: re.compile(rf"{c}\s*:\s*\**\s*([AB])\b", re.I) for c in ("STYLE", "CONTENT", "OVERALL")}


def parse(resp, c):
    """Take the LAST occurrence (the verdict line after the reasoning)."""
    ms = _PAT[c].findall(resp)
    return ms[-1].upper() if ms else None


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    from transformers import AutoProcessor
    print(f"  judge={JUDGE_ID}  pair={C1} vs {C2}  prompts={N_PROMPTS}", flush=True)
    proc = AutoProcessor.from_pretrained(JUDGE_ID)
    try:
        from transformers import AutoModelForImageTextToText
        model = AutoModelForImageTextToText.from_pretrained(
            JUDGE_ID, torch_dtype=torch.bfloat16, device_map="cuda").eval()
    except Exception as e:
        print(f"  AutoModelForImageTextToText failed ({e}); trying Qwen2VL class", flush=True)
        from transformers import Qwen2VLForConditionalGeneration
        model = Qwen2VLForConditionalGeneration.from_pretrained(
            JUDGE_ID, torch_dtype=torch.bfloat16, device_map="cuda").eval()

    prompts = eval_prompts()[:N_PROMPTS]
    imgs1 = load_imgs(TAG[C1], N_PROMPTS)
    imgs2 = load_imgs(TAG[C2], N_PROMPTS)

    @torch.no_grad()
    def ask(imgA, imgB, prompt):
        msgs = [{"role": "user", "content": [
            {"type": "text", "text": RUBRIC.format(prompt=prompt)},
            {"type": "text", "text": "Image A:"}, {"type": "image", "image": imgA},
            {"type": "text", "text": "Image B:"}, {"type": "image", "image": imgB}]}]
        inp = proc.apply_chat_template(
            msgs, add_generation_prompt=True, tokenize=True,
            return_dict=True, return_tensors="pt").to(model.device)
        out = model.generate(**inp, max_new_tokens=220, do_sample=False)
        return proc.batch_decode(out[:, inp["input_ids"].shape[1]:],
                                 skip_special_tokens=True)[0]

    crit = ("STYLE", "CONTENT", "OVERALL")
    posA = {c: 0 for c in crit}
    posTot = {c: 0 for c in crit}
    per_prompt = [{c: {} for c in crit} for _ in range(N_PROMPTS)]   # [i][crit][order]=config
    records = []

    for i in range(N_PROMPTS):
        for order, (A_label, B_label, Aimg, Bimg) in enumerate([
                (C1, C2, imgs1[i], imgs2[i]), (C2, C1, imgs2[i], imgs1[i])]):
            resp = ask(Aimg, Bimg, prompts[i])
            rec = {"prompt": prompts[i], "order": "C1C2" if order == 0 else "C2C1",
                   "raw": resp.strip()}
            for c in crit:
                pick = parse(resp, c)
                rec[c] = pick
                if pick in ("A", "B"):
                    posTot[c] += 1
                    if pick == "A":
                        posA[c] += 1
                    per_prompt[i][c][order] = A_label if pick == "A" else B_label
            records.append(rec)
        if (i + 1) % 10 == 0 or SMOKE:
            print(f"    judged {i+1}/{N_PROMPTS}", flush=True)

    # MT-Bench-style: a config wins a PROMPT on a criterion only if preferred in
    # BOTH orders; a split (order-dependent) result is a tie.
    lines = ["=" * 80,
             f"  VLM judge ({JUDGE_ID})  {C1} vs {C2}  | {N_PROMPTS} prompts, both orders",
             "  consistent win = preferred in BOTH orders; tie = order-dependent", "-" * 80,
             f"{'criterion':<10}{C1+' win%':>11}{C2+' win%':>11}{'tie%':>8}"
             f"{C1+' CI(decisive)':>22}{'posbias(A%)':>13}"]
    summary = {}
    for c in crit:
        c1w = c2w = tie = 0
        for i in range(N_PROMPTS):
            o = per_prompt[i][c]
            if 0 not in o or 1 not in o:
                continue
            if o[0] == C1 and o[1] == C1:
                c1w += 1
            elif o[0] == C2 and o[1] == C2:
                c2w += 1
            else:
                tie += 1
        n = max(1, c1w + c2w + tie)
        dec = c1w + c2w
        wr = c1w / dec if dec else float("nan")
        lo, hi = wilson(c1w, dec)
        pb = posA[c] / posTot[c] if posTot[c] else float("nan")
        summary[c] = {"c1_consistent_win": c1w, "c2_consistent_win": c2w, "tie": tie,
                      "n_prompts": c1w + c2w + tie, "c1_winrate_decisive": wr,
                      "ci95": [lo, hi], "posbias_A": pb}
        lines.append(f"{c:<10}{100*c1w/n:>10.1f}%{100*c2w/n:>10.1f}%{100*tie/n:>7.1f}%"
                     f"{f'[{lo*100:.0f},{hi*100:.0f}]':>22}{pb*100:>12.1f}%")
    report = "\n".join(lines)
    print("\n" + report)
    (OUT / f"judge_{C1}_vs_{C2}.txt").write_text(report + "\n", encoding="utf-8")
    (OUT / f"judge_{C1}_vs_{C2}.json").write_text(json.dumps(
        {"judge": JUDGE_ID, "pair": [C1, C2], "summary": summary, "records": records},
        indent=2), encoding="utf-8")
    print(f"\n  saved -> {OUT}/judge_{C1}_vs_{C2}.txt (+ .json)")


if __name__ == "__main__":
    main()
