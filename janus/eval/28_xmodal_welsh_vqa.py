Z = 1.959963984540054
SEP = "=" * 64


def wilson(k, n, z=Z):
    if not n:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = (z / d) * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (c - h, c + h)


def _first_id(tok, s):
    ids = tok.encode(s, add_special_tokens=False)
    return ids[0]


@torch.no_grad()
def yesno(model, proc, image, question):
    msgs = [{"role": "user", "content": [{"type": "image"},
                                         {"type": "text", "text": question}]}]
    prompt = proc.apply_chat_template(msgs, add_generation_prompt=True)
    inputs = proc(text=prompt, images=[image.convert("RGB")],
                  return_tensors="pt").to(model.device)
    if "pixel_values" in inputs:
        inputs["pixel_values"] = inputs["pixel_values"].to(torch.bfloat16)
    out = model(**inputs)
    logits = (out.logits if hasattr(out, "logits") else out[0])[0, -1].float()
    logp = F.log_softmax(logits, dim=-1)
    tok = proc.tokenizer
    lp_yes = max(logp[_first_id(tok, t)].item() for t in (" Yes", "Yes", " yes"))
    lp_no = max(logp[_first_id(tok, t)].item() for t in (" No", "No", " no"))
    return "yes" if lp_yes > lp_no else "no"


def main():
    if not ADAPTER:
        raise SystemExit("set ADAPTER=/path/to/adapter_best")
    (OUT / "images").mkdir(parents=True, exist_ok=True)
    from transformers import JanusForConditionalGeneration, JanusProcessor
    from peft import PeftModel
    print(f"{SEP}\n  Exp C: Welsh VQA (understanding) | ADAPTER={ADAPTER}\n"
          f"  items={len(ITEMS)}\n{SEP}", flush=True)
    proc = JanusProcessor.from_pretrained(MODEL_ID)
    base = JanusForConditionalGeneration.from_pretrained(
        MODEL_ID, torch_dtype=torch.bfloat16).to("cuda")
    model = PeftModel.from_pretrained(base, ADAPTER)
    model.eval()

    # 1) build the eval images once (base model), cache to disk
    images = []
    for i, (img_prompt, _) in enumerate(ITEMS):
        p = OUT / "images" / f"img{i:02d}.png"
        if p.exists():
            from PIL import Image
            images.append(Image.open(p).convert("RGB"))
        else:
            with model.disable_adapter():
                torch.manual_seed(SEED + i)
                img = generate_image(model, proc, img_prompt)
            img.save(p)
            images.append(img)
        print(f"  image {i+1}/{len(ITEMS)} ready: {img_prompt[:40]!r}", flush=True)

    # 2) answer in 4 conditions, score vs gold
    conds = ["base_en", "base_cy", "adapter_en", "adapter_cy"]
    correct = {c: 0 for c in conds}
    total = 0
    records = []
    for i, (img_prompt, qs) in enumerate(ITEMS):
        for (q_en, q_cy, gold) in qs:
            total += 1
            rec = {"img": img_prompt, "q_en": q_en, "q_cy": q_cy, "gold": gold}
            with model.disable_adapter():
                rec["base_en"] = yesno(model, proc, images[i], q_en + ANSWER_FMT)
                rec["base_cy"] = yesno(model, proc, images[i], q_cy + ANSWER_FMT)
            rec["adapter_en"] = yesno(model, proc, images[i], q_en + ANSWER_FMT)
            rec["adapter_cy"] = yesno(model, proc, images[i], q_cy + ANSWER_FMT)
            for c in conds:
                if rec[c] == gold:
                    correct[c] += 1
            records.append(rec)
        print(f"  answered item {i+1}/{len(ITEMS)}", flush=True)

    summ = {}
    for c in conds:
        acc = correct[c] / total if total else float("nan")
        lo, hi = wilson(correct[c], total)
        summ[c] = {"acc": acc, "n": total, "ci95": [lo, hi]}

    report = [SEP, "  Exp C: Welsh VQA accuracy (yes/no, logit-scored)",
              f"  n_questions={total}", SEP]
    for c in conds:
        s = summ[c]
        report.append(f"  {c:<12} {s['acc']*100:5.1f}%  CI[{s['ci95'][0]*100:.0f},{s['ci95'][1]*100:.0f}]")
    report += [
        "-" * 64,
        f"  comprehension gap (base_en - base_cy)   : "
        f"{(summ['base_en']['acc']-summ['base_cy']['acc'])*100:+.1f} pts",
        f"  transfer (adapter_cy - base_cy)         : "
        f"{(summ['adapter_cy']['acc']-summ['base_cy']['acc'])*100:+.1f} pts",
        f"  no-harm control (adapter_en - base_en)  : "
        f"{(summ['adapter_en']['acc']-summ['base_en']['acc'])*100:+.1f} pts",
        SEP]
    text = "\n".join(report)
    print("\n" + text)
    (OUT / "expC_results.txt").write_text(text + "\n", encoding="utf-8")
    (OUT / "expC_results.json").write_text(json.dumps(
        {"summary": summ, "records": records}, indent=2), encoding="utf-8")
    print(f"\n  saved -> {OUT}/expC_results.txt (+ .json, images/)")


if __name__ == "__main__":
    main()
